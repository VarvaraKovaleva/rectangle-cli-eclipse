package ru.oivt.rectanglecli.model;

/**
 * Общий интерфейс для всех геометрических фигур.
 * Позволяет работать с разными фигурами через единый тип (полиморфизм).
 */
public interface Shape {

    //Название фигуры для вывода пользователю
    String getName();

    //Площадь фигуры
    double area();

    //Периметр (или длина границы) фигуры
    double perimeter();
}